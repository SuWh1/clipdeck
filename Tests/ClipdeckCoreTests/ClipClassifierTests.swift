import Foundation
import Testing
@testable import ClipdeckCore

@Suite("ClipClassifier")
struct ClipClassifierTests {
    private let classifier = ClipClassifier(ignoredBundleIDs: ["com.example.vault"])
    private let source = ClipSource(bundleID: "com.apple.Safari", name: "Safari")

    private func snapshot(
        types: [String], string: String? = nil, rtf: Data? = nil,
        image: Data? = nil, files: [URL] = [], url: String? = nil
    ) -> PasteboardSnapshot {
        PasteboardSnapshot(types: types, string: string, rtf: rtf, imageData: image, fileURLs: files, urlString: url)
    }

    @Test("should classify plain text as text")
    func plainText() {
        let result = classifier.classify(snapshot(types: ["public.utf8-plain-text"], string: "hello world"), source: source)
        #expect(result?.kind == .text)
        #expect(result?.text == "hello world")
        #expect(result?.source == source)
    }

    @Test("should keep rich text data next to the text")
    func richText() {
        let rtf = Data("{\\rtf1 hello}".utf8)
        let result = classifier.classify(
            snapshot(types: ["public.rtf", "public.utf8-plain-text"], string: "hello", rtf: rtf), source: source
        )
        #expect(result?.kind == .text)
        #expect(result?.rtf == rtf)
    }

    @Test("should classify a single web address as a link", arguments: [
        "https://example.com/path?q=1", "http://localhost:3000", "  https://example.com  \n",
    ])
    func link(text: String) {
        let result = classifier.classify(snapshot(types: ["public.utf8-plain-text"], string: text), source: source)
        #expect(result?.kind == .link)
        #expect(result?.text == text.trimmingCharacters(in: .whitespacesAndNewlines))
    }

    @Test("should keep text that only contains an address as text", arguments: [
        "see https://example.com for more", "example.com", "file:///Users/me/a.txt", "https://",
    ])
    func notLink(text: String) {
        let result = classifier.classify(snapshot(types: ["public.utf8-plain-text"], string: text), source: source)
        #expect(result?.kind == .text)
    }

    @Test("should classify a public url entry as a link")
    func publicURL() {
        let result = classifier.classify(
            snapshot(types: ["public.url"], url: "https://example.com"), source: source
        )
        #expect(result?.kind == .link)
        #expect(result?.text == "https://example.com")
    }

    @Test("should skip whitespace-only text")
    func whitespace() {
        #expect(classifier.classify(snapshot(types: ["public.utf8-plain-text"], string: " \n\t "), source: source) == nil)
    }

    @Test("should skip an empty pasteboard")
    func empty() {
        #expect(classifier.classify(snapshot(types: []), source: source) == nil)
    }

    @Test("should skip copies marked as secret or temporary", arguments: [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ])
    func concealed(marker: String) {
        let result = classifier.classify(
            snapshot(types: ["public.utf8-plain-text", marker], string: "hunter2"), source: source
        )
        #expect(result == nil)
    }

    @Test("should skip copies made in ignored apps")
    func ignoredApp() {
        let vault = ClipSource(bundleID: "com.example.vault", name: "Vault")
        #expect(classifier.classify(snapshot(types: ["public.utf8-plain-text"], string: "secret"), source: vault) == nil)
    }

    @Test("should classify copied files with their paths")
    func files() {
        let urls = [URL(fileURLWithPath: "/tmp/a.txt"), URL(fileURLWithPath: "/tmp/b c.png")]
        let result = classifier.classify(
            snapshot(types: ["public.file-url", "public.utf8-plain-text", "public.tiff"], string: "a.txt", image: TestImages.tiff(), files: urls),
            source: source
        )
        #expect(result?.kind == .file)
        #expect(result?.text == "/tmp/a.txt\n/tmp/b c.png")
        #expect(result?.filePaths == ["/tmp/a.txt", "/tmp/b c.png"])
    }

    @Test("should save a single copied image file as an image")
    func imageFile() throws {
        let url = makeTempDirectory().appendingPathComponent("photo.png")
        try TestImages.png(width: 6, height: 2).write(to: url)
        let result = classifier.classify(snapshot(types: ["public.file-url"], files: [url]), source: source)
        #expect(result?.kind == .image)
        #expect(result?.text == "")
        #expect(result?.image?.width == 6)
        #expect(result?.image?.png == TestImages.png(width: 6, height: 2))
    }

    @Test("should read an image file through a link to a file without an extension")
    func linkedImageFile() throws {
        let directory = makeTempDirectory()
        let target = directory.appendingPathComponent("cache-entry")
        let link = directory.appendingPathComponent("photo.jpg")
        try TestImages.png().write(to: target)
        try FileManager.default.createSymbolicLink(at: link, withDestinationURL: target)
        let result = classifier.classify(snapshot(types: ["public.file-url"], files: [link]), source: source)
        #expect(result?.kind == .image)
    }

    @Test("should save an image file and the same copied picture as one clip")
    func imageFileMatchesPicture() throws {
        let url = makeTempDirectory().appendingPathComponent("photo.png")
        try TestImages.png().write(to: url)
        let fromFile = classifier.classify(snapshot(types: ["public.file-url"], files: [url]), source: source)
        let fromPicture = classifier.classify(snapshot(types: ["public.png"], image: TestImages.png()), source: source)
        #expect(fromFile?.contentHash == fromPicture?.contentHash)
    }

    @Test("should keep a folder or a pipe named like an image as a file", .timeLimit(.minutes(1)))
    func specialFileNamedLikeImage() throws {
        let directory = makeTempDirectory()
        let folder = directory.appendingPathComponent("album.png")
        let pipe = directory.appendingPathComponent("stream.png")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: false)
        #expect(mkfifo(pipe.path, 0o600) == 0)
        for url in [folder, pipe] {
            #expect(classifier.classify(snapshot(types: ["public.file-url"], files: [url]), source: source)?.kind == .file)
        }
    }

    @Test("should keep a copied file as a file when it is not a readable image", arguments: [
        "notes.txt", "missing.png", "broken.png",
    ])
    func notImageFile(name: String) throws {
        let url = makeTempDirectory().appendingPathComponent(name)
        if name != "missing.png" {
            try Data("not an image".utf8).write(to: url)
        }
        let result = classifier.classify(snapshot(types: ["public.file-url"], files: [url]), source: source)
        #expect(result?.kind == .file)
        #expect(result?.text == url.path)
    }

    @Test("should keep an image file over the size limit as a file")
    func largeImageFile() throws {
        let url = makeTempDirectory().appendingPathComponent("photo.png")
        try TestImages.png().write(to: url)
        let small = ClipClassifier(ignoredBundleIDs: [], maxImageBytes: 10)
        #expect(small.classify(snapshot(types: ["public.file-url"], files: [url]), source: source)?.kind == .file)
    }

    @Test("should classify an image-only copy as an image with png data and size")
    func imageOnly() {
        let result = classifier.classify(snapshot(types: ["public.tiff"], image: TestImages.tiff(width: 5, height: 2)), source: source)
        #expect(result?.kind == .image)
        #expect(result?.image?.width == 5)
        #expect(result?.image?.height == 2)
        #expect(result?.image?.png.starts(with: [0x89, 0x50, 0x4E, 0x47]) == true)
    }

    @Test("should keep png data unchanged so repeated copies match")
    func pngUnchanged() {
        let png = TestImages.png()
        let result = classifier.classify(snapshot(types: ["public.png"], image: png), source: source)
        #expect(result?.image?.png == png)
    }

    @Test("should prefer text when the text comes before the image")
    func spreadsheetCells() {
        let result = classifier.classify(
            snapshot(types: ["public.utf8-plain-text", "public.png"], string: "A1\tB1", image: TestImages.png()),
            source: source
        )
        #expect(result?.kind == .text)
    }

    @Test("should prefer the image when the image comes first")
    func browserImage() {
        let result = classifier.classify(
            snapshot(types: ["public.tiff", "public.utf8-plain-text"], string: "photo.jpg", image: TestImages.tiff()),
            source: source
        )
        #expect(result?.kind == .image)
    }

    @Test("should fall back to text when the image data cannot be read")
    func brokenImage() {
        let result = classifier.classify(
            snapshot(types: ["public.tiff", "public.utf8-plain-text"], string: "caption", image: Data([1, 2, 3])),
            source: source
        )
        #expect(result?.kind == .text)
        #expect(result?.text == "caption")
    }

    @Test("should skip images larger than the size limit")
    func hugeImage() {
        let small = ClipClassifier(ignoredBundleIDs: [], maxImageBytes: 10)
        #expect(small.classify(snapshot(types: ["public.png"], image: TestImages.png()), source: source) == nil)
    }

    @Test("should skip an image with more pixels than it can safely decode")
    func skipsHugePixelCount() {
        let png = TestImages.encode(TestImages.image(width: 20, height: 20), as: .png)
        let copy = snapshot(types: ["public.png"], image: png)
        #expect(ClipClassifier(ignoredBundleIDs: [], maxImagePixels: 399).classify(copy, source: nil) == nil)
        #expect(ClipClassifier(ignoredBundleIDs: [], maxImagePixels: 400).classify(copy, source: nil)?.kind == .image)
    }

    @Test("should drop rich text formatting over the text limit but keep the text")
    func dropsHugeRichText() {
        let small = ClipClassifier(ignoredBundleIDs: [], maxTextBytes: 10)
        let copy = snapshot(types: ["public.rtf", "public.utf8-plain-text"], string: "hello", rtf: Data(count: 11))
        let result = small.classify(copy, source: nil)
        #expect(result?.text == "hello")
        #expect(result?.rtf == nil)
    }

    @Test("should skip text longer than the size limit")
    func hugeText() {
        let small = ClipClassifier(ignoredBundleIDs: [], maxTextBytes: 4)
        #expect(small.classify(snapshot(types: ["public.utf8-plain-text"], string: "hello"), source: source) == nil)
    }
}

@Suite("ClipCandidate")
struct ClipCandidateTests {
    @Test("should give identical content the same hash")
    func sameHash() {
        #expect(textCandidate("a").contentHash == textCandidate("a", source: nil).contentHash)
    }

    @Test("should give different content or kinds different hashes")
    func differentHash() {
        let link = ClipCandidate(kind: .link, text: "a")
        #expect(textCandidate("a").contentHash != textCandidate("b").contentHash)
        #expect(textCandidate("a").contentHash != link.contentHash)
        #expect(imageCandidate(width: 4).contentHash != imageCandidate(width: 5).contentHash)
    }

    @Test("should build search text from content and app name, folded for case and accents")
    func searchText() {
        let candidate = textCandidate("Привет Café", source: ClipSource(bundleID: nil, name: "Telegram"))
        #expect(candidate.searchText == "привет cafe\ntelegram")
    }
}
